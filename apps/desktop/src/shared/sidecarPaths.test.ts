import { describe, expect, it } from 'vitest'
import { allowedSidecarPath } from './sidecarPaths'

describe('sidecar path allowlist', () => {
  it('allows decision settings, shadow, and paginated logs', () => {
    expect(allowedSidecarPath('GET', '/settings/decision')).toBe(true)
    expect(allowedSidecarPath('POST', '/settings/decision')).toBe(true)
    expect(allowedSidecarPath('POST', '/decision/shadow')).toBe(true)
    expect(allowedSidecarPath('GET', '/decision/logs?limit=20&offset=0')).toBe(true)
    expect(allowedSidecarPath('POST', '/decision/logs')).toBe(false)
  })

  it('allows library import, list, delete, and reindex', () => {
    expect(allowedSidecarPath('GET', '/library/items')).toBe(true)
    expect(allowedSidecarPath('POST', '/library/import')).toBe(true)
    expect(allowedSidecarPath('DELETE', '/library/items/4')).toBe(true)
    expect(allowedSidecarPath('POST', '/index/rebuild')).toBe(true)
    expect(allowedSidecarPath('POST', '/search')).toBe(true)
    expect(allowedSidecarPath('DELETE', '/library/items/nope')).toBe(false)
    expect(allowedSidecarPath('GET', '/library/import')).toBe(false)
  })

  it('allows the M7 memory, import channel, style and preference routes', () => {
    expect(allowedSidecarPath('GET', '/conversations?limit=200')).toBe(true)
    expect(allowedSidecarPath('POST', '/conversations')).toBe(true)
    expect(allowedSidecarPath('GET', '/conversations/12')).toBe(true)
    expect(allowedSidecarPath('PATCH', '/conversations/12')).toBe(true)
    expect(allowedSidecarPath('DELETE', '/conversations/12')).toBe(true)
    expect(allowedSidecarPath('POST', '/conversations/12/fork')).toBe(true)
    expect(allowedSidecarPath('POST', '/conversations/clear')).toBe(true)
    expect(allowedSidecarPath('GET', '/conversations/12/export?format=md')).toBe(true)
    expect(allowedSidecarPath('GET', '/folders')).toBe(true)
    expect(allowedSidecarPath('PATCH', '/folders/3')).toBe(true)
    expect(allowedSidecarPath('GET', '/projects')).toBe(true)
    expect(allowedSidecarPath('GET', '/import/sources?locale=en')).toBe(true)
    expect(allowedSidecarPath('POST', '/import/sources/obsidian/browse')).toBe(true)
    expect(allowedSidecarPath('POST', '/import/documents')).toBe(true)
    expect(allowedSidecarPath('GET', '/styles?locale=zh')).toBe(true)
    expect(allowedSidecarPath('GET', '/settings/app')).toBe(true)
    expect(allowedSidecarPath('POST', '/settings/ui')).toBe(true)
    expect(allowedSidecarPath('DELETE', '/conversations/abc')).toBe(false)
    expect(allowedSidecarPath('GET', '/import/documents')).toBe(false)
  })

  it('still allows chat and clarify, and blocks other routes', () => {
    expect(allowedSidecarPath('POST', '/chat')).toBe(true)
    expect(allowedSidecarPath('POST', '/ask')).toBe(true)
    expect(allowedSidecarPath('GET', '/settings/ask')).toBe(true)
    expect(allowedSidecarPath('POST', '/settings/ask')).toBe(true)
    expect(allowedSidecarPath('GET', '/ask')).toBe(false)
    expect(allowedSidecarPath('GET', '/clarify/active')).toBe(true)
    expect(allowedSidecarPath('POST', '/clarify/12/answer')).toBe(true)
    expect(allowedSidecarPath('POST', '/verify')).toBe(true)
    expect(allowedSidecarPath('GET', '/verify/3')).toBe(true)
    expect(allowedSidecarPath('DELETE', '/verify/3')).toBe(false)
    expect(allowedSidecarPath('GET', '/connectors')).toBe(true)
    expect(allowedSidecarPath('POST', '/connectors')).toBe(false)
    expect(allowedSidecarPath('GET', '/connectors/ima/bases')).toBe(true)
    expect(allowedSidecarPath('GET', '/connectors/ima/folders')).toBe(true)
    expect(allowedSidecarPath('POST', '/connectors/ima/search')).toBe(true)
    expect(allowedSidecarPath('POST', '/connectors/ima/import')).toBe(true)
    expect(allowedSidecarPath('GET', '/settings/ima')).toBe(true)
    expect(allowedSidecarPath('POST', '/settings/ima')).toBe(true)
    expect(allowedSidecarPath('DELETE', '/connectors/2')).toBe(true)
    expect(allowedSidecarPath('DELETE', '/decision/logs')).toBe(false)
  })
})
